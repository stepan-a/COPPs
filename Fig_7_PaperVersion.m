% Script to create Figure 7 in
% **de Groot, O., F. Mazelis, R. Motto, A. Ristiniemi**
% "A Toolkit for Computing Constrained Optimal Policy Projections (COPPs)"
%% Preamble
clear
% Dynare (with the copps package) must be in the MATLAB path.
root = pwd;

%% Run individual script
% Fig_7_a (formerly IndividualProjections/Run_COPPs_Fig_7_a.m)
siggma = 1;
varphi = 5;
theta  = 3/4;
betta  = 0.99;
alppha = 1/4;
epsilon= 9;
Omega  = (1-alppha)/(1-alppha+alppha*epsilon);       %defined on page 60
lambda = (1-theta)*(1-betta*theta)/theta*Omega;      %defined on page 61
kappa  = lambda*(siggma+(varphi+alppha)/(1-alppha)); %defined on page 63
vartheta= kappa/epsilon;
alpha_x = kappa/epsilon;
cd(fullfile(root, 'Models/GaliNK3_ZLB'))
dynare NK3ZLB -DSMOOTHER nograph noclearall
oo_ = copps.solve(M_, oo_, 'name',                          'Fig_7_a', ...
                           'planner_discount_factor',       'betta', ...
                           'loss_function_variables',       {'pinf';'og'}, ...
                           'policy_instruments_and_shocks', {'r','er'}, ...
                           'past_periods',                  50, ...
                           'alpha',                         1, ...
                           't_loss',                        60, ...
                           'h_policy',                      60, ...
                           'constraint',                    'ON', ...
                           'rate_min',                      0, ... % ELB in annual policy rate
                           'policy_rate_steady_state',      0, ...
                           'loss_function_weights',         [1,alpha_x]);
cd(root)
projections_all.simple_rules = oo_.copps.Fig_7_a.simple_rules;
projections_all.COPPs_7a = oo_.copps.Fig_7_a.COPPs;
%% Run individual script
% Fig_7_b (formerly IndividualProjections/Run_COPPs_Fig_7_b.m)
siggma = 1;
varphi = 5;
theta  = 3/4;
betta  = 0.99;
alppha = 1/4;
epsilon= 9;
Omega  = (1-alppha)/(1-alppha+alppha*epsilon);       %defined on page 60
lambda = (1-theta)*(1-betta*theta)/theta*Omega;      %defined on page 61
kappa  = lambda*(siggma+(varphi+alppha)/(1-alppha)); %defined on page 63
vartheta= kappa/epsilon;
alpha_x = kappa/epsilon;
cd(fullfile(root, 'Models/GaliNK3_ZLB'))
oo_ = copps.solve(M_, oo_, 'name',                          'Fig_7_b', ...
                           'planner_discount_factor',       'betta', ...
                           'loss_function_variables',       {'pinf';'og'}, ...
                           'policy_instruments_and_shocks', {'r','er'}, ...
                           'past_periods',                  50, ...
                           'alpha',                         1, ...
                           't_loss',                        60, ...
                           'h_policy',                      60, ...
                           'constraint',                    'ON', ...
                           'rate_min',                      0, ... % ELB in annual policy rate
                           'policy_rate_steady_state',      0, ...
                           'rate_dev_min',                  .25*ones(1,60), ...
                           'rate_dev_max',                  .25*ones(1,60), ...
                           'loss_function_weights',         [1,alpha_x]);
cd(root)
projections_all.COPPs_7b = oo_.copps.Fig_7_b.COPPs;
clear params
%% Set preferences
params.plotting.Data = {projections_all.simple_rules.data   , '-'  , 1 ,[0,0,0], 'Baseline' ; ...
        projections_all.COPPs_7a.data          , '--' , 1 ,[0,0,1], 'Commitment'; ...
        projections_all.COPPs_7b.data          , '-.'  , 1 ,[0,1,0],'Small deviations'; ...
        };

params.plotting.VarsToPlot = {...
    'pi_ann',[-40,4],'Inflation'  ;...
    'og'    ,[-30,2],'Output gap' ;...
    'r_ann' ,[-1,5] ,'Policy rate';...
    };

params.plotting.P_past   = 4;
params.plotting.P_future = 17;

%% Plot chart
copps.plot(projections_all, params);
