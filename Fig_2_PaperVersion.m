% Script to create Figure 2 in
% **de Groot, O., F. Mazelis, R. Motto, A. Ristiniemi**
% "A Toolkit for Computing Constrained Optimal Policy Projections (COPPs)"
%% Preamble
clear
% Dynare (with the copps package) must be in the MATLAB path.
root = pwd;

%% Run individual script
% Fig_2_a (formerly IndividualProjections/Run_COPPs_Fig_2_a.m)
kappa   = 0.1275;
epsilon = 6;
alpha_x = kappa/epsilon;
cd(fullfile(root, 'Models/GaliNK3'))
dynare GaliNK3 -DSMOOTHER nograph noclearall
plotting.VarsToPlot = {...
    'pinf_ann',[-4,1],'Inflation'  ;...
    'og'      ,[-4,1],'Output gap' ;...
    'r_ann'   ,[-1,5],'Policy rate';...
    };
oo_ = copps.solve(M_, oo_, 'name',                          'Fig_2_a', ...
                           'planner_discount_factor',       'beta', ...
                           'loss_function_variables',       {'pinf';'og'}, ...
                           'policy_instruments_and_shocks', {'r','er'}, ...
                           'past_periods',                  50, ...
                           'alpha',                         1, ...
                           't_loss',                        60, ...
                           'h_policy',                      60, ...
                           'loss_function_weights',         [1,alpha_x], ...
                           'plotting',                      plotting);
cd(root)
params = oo_.copps.Fig_2_a.params;
params.plotting.P_past   = 4;
params.plotting.P_future = 41;
copps.plot(oo_.copps.Fig_2_a, params);
projections_all.simple_rules = oo_.copps.Fig_2_a.simple_rules;
projections_all.COPPs_2a = oo_.copps.Fig_2_a.COPPs;
%% Run individual script
% Fig_2_b (formerly IndividualProjections/Run_COPPs_Fig_2_b.m)
kappa   = 0.1275;
epsilon = 6;
alpha_x = kappa/epsilon;
cd(fullfile(root, 'Models/GaliNK3'))
oo_ = copps.solve(M_, oo_, 'name',                          'Fig_2_b', ...
                           'planner_discount_factor',       'beta', ...
                           'loss_function_variables',       {'pinf';'og'}, ...
                           'policy_instruments_and_shocks', {'r','er'}, ...
                           'past_periods',                  50, ...
                           'alpha',                         1, ...
                           't_loss',                        60, ...
                           'h_policy',                      60, ...
                           'policy_type',                   'DIS', ...
                           'loss_function_weights',         [1,alpha_x]);
cd(root)
projections_all.COPPs_2b = oo_.copps.Fig_2_b.COPPs;
clear params
%% Set preferences
params.plotting.Data = {projections_all.simple_rules.data   , '-'  , 1 ,[0,0,0], 'Baseline' ; ...
        projections_all.COPPs_2a.data          , '--' , 1 ,[0,0,1], 'Commitment'; ...
        projections_all.COPPs_2b.data          , '--' , 1 ,[0,0,1], 'Discretion'; ...
        };

params.plotting.VarsToPlot = {...
    'pinf_ann',[-4,1],'Inflation'  ;...
    'og'      ,[-4,1],'Output gap' ;...
    'r_ann'   ,[-1,5],'Policy rate';...
    };
params.plotting.P_past   = 4;
params.plotting.P_future = 41;

%% Plot chart
copps.plot(projections_all, params);
