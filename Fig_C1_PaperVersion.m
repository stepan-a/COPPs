% Script to create Figure C1 in
% **de Groot, O., F. Mazelis, R. Motto, A. Ristiniemi**
% "A Toolkit for Computing Constrained Optimal Policy Projections (COPPs)"
%% Preamble
clear
% Dynare (with the copps package) must be in the MATLAB path.
root = pwd;

%% Run individual script
% Fig_C1_a (formerly IndividualProjections/Run_COPPs_Fig_C1_a.m)
kappa   = 0.1275;
epsilon = 6;
alpha_x = kappa/epsilon;
cd(fullfile(root, 'Models/GaliNK3'))
dynare GaliNK3_costpush_iid -DSMOOTHER nograph noclearall
oo_ = copps.solve(M_, oo_, 'name',                          'Fig_C1_a', ...
                           'planner_discount_factor',       'beta', ...
                           'loss_function_variables',       {'pinf';'og'}, ...
                           'policy_instruments_and_shocks', {'r','er'}, ...
                           'past_periods',                  50, ...
                           'alpha',                         1, ...
                           't_loss',                        60, ...
                           'h_policy',                      60, ...
                           'loss_function_weights',         [1,alpha_x]);
cd(root)
projections_all.simple_rules = oo_.copps.Fig_C1_a.simple_rules;
projections_all.COPPs_C1a = oo_.copps.Fig_C1_a.COPPs;
%% Run individual script
% Fig_C1_b (formerly IndividualProjections/Run_COPPs_Fig_C1_b.m)
kappa   = 0.1275;
epsilon = 6;
alpha_x = kappa/epsilon;
cd(fullfile(root, 'Models/GaliNK3'))
oo_ = copps.solve(M_, oo_, 'name',                          'Fig_C1_b', ...
                           'planner_discount_factor',       'beta', ...
                           'loss_function_variables',       {'pinf';'og'}, ...
                           'policy_instruments_and_shocks', {'r','er'}, ...
                           'past_periods',                  50, ...
                           'alpha',                         1, ...
                           't_loss',                        60, ...
                           'h_policy',                      60, ...
                           'policy_type',                   'DIS', ...
                           'loss_function_weights',         [1,alpha_x]);
cd(root)
projections_all.COPPs_C1b = oo_.copps.Fig_C1_b.COPPs;
clear params
%% Set preferences
params.plotting.Data = {projections_all.simple_rules.data   , '-'  , 1 ,[0,0,0], 'Baseline' ; ...
        projections_all.COPPs_C1a.data          , '--'  , 1 ,[0,0,1],'Commitment'; ...
        projections_all.COPPs_C1b.data          , '-.' , 1 ,[0,1,0], 'Discretion'; ...
        };

params.plotting.VarsToPlot = {...
    'pinf_ann',[-2,4] ,'Inflation'  ;...
    'og'      ,[-4,2] ,'Output gap' ;...
    'r_ann'   ,[-2,12],'Policy rate';...
    };

params.plotting.P_past   = 4;
params.plotting.P_future = 9;

%% Plot chart
copps.plot(projections_all, params);
